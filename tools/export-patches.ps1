# Regenerates patches/ from the local codex-bridge development clone.
#
# The patches are the fork commit chain rebased on an upstream release:
#   <Base>..<Head>  ->  patches/001..N (one plain `git diff -U0` per commit,
# applied in file-name order by .github/workflows/codex-bridge-portable-build.yml).
#
# Zero context (-U0) is deliberate: unmodified upstream lines may contain
# non-ASCII text, and this repository must stay ASCII-only. The workflow
# applies the patches with `git apply --unidiff-zero` and then verifies every
# touched file against patches/patched-files.txt, the blob-id manifest this
# script writes next to the patches.
#
# Usage (from a machine with the codex-bridge clone next to this repo):
#   pwsh -File tools\export-patches.ps1
#   pwsh -File tools\export-patches.ps1 -Repo D:\codex-bridge -Head win
#
# After a re-baseline (upstream moved and the 8 commits were rebased onto the
# new upstream head), just run this again: <Base> defaults to the merge-base
# of <Head> and origin/win, which is exactly the upstream anchor.
param(
  [string]$Repo = (Join-Path $PSScriptRoot "..\..\codex-bridge"),
  [string]$Head = "win",
  [string]$Base = "",
  [string]$OutDir = (Join-Path $PSScriptRoot "..\patches")
)

$ErrorActionPreference = 'Stop'
$Repo = (Resolve-Path -LiteralPath $Repo).Path

if (-not $Base) {
  $Base = (& git -C $Repo merge-base $Head origin/win | Select-Object -First 1)
  if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($Base)) {
    throw "cannot resolve merge-base of '$Head' and 'origin/win'; pass -Base explicitly"
  }
  $Base = $Base.Trim()
}

$commits = @(& git -C $Repo log --reverse --format="%H%x09%s" "$Base..$Head")
if ($LASTEXITCODE -ne 0) { throw "git log failed for $Base..$Head" }
if ($commits.Count -eq 0) { throw "no commits in $Base..$Head" }

New-Item -ItemType Directory -Path $OutDir -Force | Out-Null
Get-ChildItem -LiteralPath $OutDir -Filter '*.patch' | Remove-Item -Force

Write-Host "anchor (base): $Base"
$i = 0
foreach ($line in $commits) {
  $parts = $line -split "`t", 2
  $sha = $parts[0]
  $subject = $parts[1]
  $i++

  $words = @(($subject -replace '^dan:\s*', '') -replace '[^A-Za-z0-9]+', ' ' -split '\s+' | Where-Object { $_ })
  $slug = $words[0].ToLowerInvariant()
  foreach ($word in $words[1..($words.Count - 1)]) {
    $candidate = "$slug-$($word.ToLowerInvariant())"
    if ($candidate.Length -le 48) { $slug = $candidate } else { break }
  }

  $name = '{0:d3}-{1}.patch' -f $i, $slug
  $path = Join-Path $OutDir $name
  & git -C $Repo diff -U0 --no-ext-diff "--output=$path" "$sha^" $sha
  if ($LASTEXITCODE -ne 0) { throw "git diff failed for $sha" }
  Write-Host ('wrote {0} <- {1} {2}' -f $name, $sha.Substring(0, 8), $subject)
}

Write-Host "patches written: $i -> $((Resolve-Path -LiteralPath $OutDir).Path)"

$changed = @(& git -C $Repo diff --name-only $Base $Head)
if ($LASTEXITCODE -ne 0) { throw "git diff --name-only failed for $Base..$Head" }
$manifestLines = foreach ($relative in ($changed | Sort-Object)) {
  $blob = @(& git -C $Repo rev-parse ($Head + ':' + $relative))[0]
  if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($blob)) {
    throw "cannot resolve blob for '$relative' at $Head"
  }
  ('{0} {1}' -f $blob.ToString().Trim(), $relative)
}
$manifestPath = Join-Path $OutDir 'patched-files.txt'
$header = '# Git blob ids of every file that the patches change.' + "`n" + '# Generated by tools/export-patches.ps1; verified by the workflow after applying.'
$manifestText = $header + "`n" + (($manifestLines -join "`n")) + "`n"
[IO.File]::WriteAllText($manifestPath, $manifestText, [Text.UTF8Encoding]::new($false))
Write-Host "manifest written: $manifestPath ($($manifestLines.Count) files)"
